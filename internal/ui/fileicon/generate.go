//go:build ignore

// Generates the file icons from a checkout of Miguel Solorio's Symbols
// icon theme (https://github.com/miguelsolorio/vscode-symbols, MIT): the
// file icons' SVGs, packed into icons.tar.gz, and the tables that map a
// file's name, its extensions and VS Code's language ids to them, in
// tables_gen.go. The folder icons are left out: the lists show files.
//
//	go run internal/ui/fileicon/generate.go <symbols checkout> <version>
//
// Then copy the checkout's LICENSE over this folder's LICENSE when it
// changed, and update the version in README.md.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type theme struct {
	IconDefinitions map[string]struct {
		IconPath string `json:"iconPath"`
	} `json:"iconDefinitions"`
	File           string            `json:"file"`
	FileExtensions map[string]string `json:"fileExtensions"`
	FileNames      map[string]string `json:"fileNames"`
	LanguageIds    map[string]string `json:"languageIds"`
}

func main() {
	if len(os.Args) != 3 {
		fail("usage: go run internal/ui/fileicon/generate.go <symbols checkout> <version>")
	}
	src, version := filepath.Join(os.Args[1], "src"), os.Args[2]
	raw, err := os.ReadFile(filepath.Join(src, "symbol-icon-theme.json"))
	check(err)
	var t theme
	check(json.Unmarshal(raw, &t))
	out := filepath.Join("internal", "ui", "fileicon")

	// icon is the file's name, without .svg, of a definition that is a
	// file icon; "" for any other.
	icon := func(def string) string {
		d, ok := t.IconDefinitions[def]
		if !ok || !strings.HasPrefix(d.IconPath, "./icons/files/") {
			return ""
		}
		return strings.TrimSuffix(path.Base(d.IconPath), ".svg")
	}
	used := map[string]bool{}
	// table maps the keys, lower-cased as VS Code matches them, to their
	// icons.
	table := func(m map[string]string) map[string]string {
		r := map[string]string{}
		for k, def := range m {
			if name := icon(def); name != "" {
				r[strings.ToLower(k)] = name
				used[name] = true
			}
		}
		return r
	}
	names, exts, langs := table(t.FileNames), table(t.FileExtensions), table(t.LanguageIds)
	def := icon(t.File)
	if def == "" {
		fail("the theme's default file icon %q is not a file icon", t.File)
	}
	used[def] = true

	// The SVGs, each on one line, packed in name order.
	var icons []string
	for name := range used {
		icons = append(icons, name)
	}
	sort.Strings(icons)
	space := regexp.MustCompile(`>\s+<`)
	var packed bytes.Buffer
	zw, err := gzip.NewWriterLevel(&packed, gzip.BestCompression)
	check(err)
	tw := tar.NewWriter(zw)
	for _, name := range icons {
		b, err := os.ReadFile(filepath.Join(src, "icons", "files", name+".svg"))
		check(err)
		b = bytes.TrimSpace(space.ReplaceAll(b, []byte("><")))
		check(tw.WriteHeader(&tar.Header{Name: name + ".svg", Mode: 0o644, Size: int64(len(b))}))
		_, err = tw.Write(b)
		check(err)
	}
	check(tw.Close())
	check(zw.Close())
	check(os.WriteFile(filepath.Join(out, "icons.tar.gz"), packed.Bytes(), 0o644))

	var g bytes.Buffer
	fmt.Fprintf(&g, "// Code generated by generate.go from Symbols %s; DO NOT EDIT.\n\npackage fileicon\n\n", version)
	fmt.Fprintf(&g, "// defaultIcon is the icon of a file no table names.\nconst defaultIcon = %q\n\n", def)
	write := func(doc, name string, m map[string]string) {
		keys := make([]string, 0, len(m))
		for k := range m {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(&g, "// %s\nvar %s = map[string]string{\n", doc, name)
		for _, k := range keys {
			fmt.Fprintf(&g, "\t%q: %q,\n", k, m[k])
		}
		g.WriteString("}\n\n")
	}
	write("byName maps a file's whole name to its icon.", "byName", names)
	write("byExtension maps a file's extensions, as \"d.ts\" or \"ts\", to its icon.", "byExtension", exts)
	write("byLanguage maps VS Code's language ids to their icons; most are an extension too.", "byLanguage", langs)
	src2, err := format.Source(g.Bytes())
	check(err)
	check(os.WriteFile(filepath.Join(out, "tables_gen.go"), src2, 0o644))
	fmt.Printf("%d icons, %d bytes packed; %d names, %d extensions, %d languages\n", len(icons), packed.Len(), len(names), len(exts), len(langs))
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(f string, a ...any) {
	fmt.Fprintf(os.Stderr, f+"\n", a...)
	os.Exit(1)
}
