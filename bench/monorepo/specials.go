func hashName(s string) uint64 {
	h := fnv.New64a()
	h.Write([]byte(s))
	return h.Sum64()
}

// hugeData writes a file whose line i depends only on i, so the second
// version can change every 97th line, insert three lines every 5003 and drop
// one every 7001 without keeping the first version around.
func hugeData(h hugeSpec, ver int) []byte {
	var b bytes.Buffer
	b.Grow(h.lines * 72)
	b.WriteString(h.prefix)
	base := hashName(h.name)
	line := func(seed uint64) {
		r := rng{s: seed, sc: h.sc}
		b.WriteString(r.expand(h.tmpl))
		b.WriteByte('\n')
	}
	for i := 0; i < h.lines; i++ {
		seed := base + uint64(i)*0x100000001b3
		if ver > 0 {
			if i%7001 == 1 {
				continue
			}
			if i%97 == 0 {
				seed ^= 0xabcdef12345
			}
			if i%5003 == 0 {
				for j := uint64(1); j <= 3; j++ {
					line(seed ^ j<<40)
				}
			}
		}
		line(seed)
	}
	b.WriteString(h.suffix)
	return b.Bytes()
}

// minified is one 20 MB line.
func minified(ver int) []byte {
	var b bytes.Buffer
	b.Grow(21 << 20)
	for i := 0; b.Len() < 20<<20; i++ {
		seed := 0x51ed270b + uint64(i)*0x100000001b3
		if ver > 0 && i%97 == 0 {
			seed ^= 0xabcdef12345
		}
		r := rng{s: seed, sc: scEnglish}
		b.WriteString(r.expand("function $a($a,$a){return $a($n)+$a*$n};"))
	}
	b.WriteByte('\n')
	return b.Bytes()
}

// blob is 100 MB that does not compress; the second version rewrites 200
// regions of 4 KB.
func blob(ver int) []byte {
	const size = 100 << 20
	out := make([]byte, size)
	r := rng{s: 0xb10b}
	for i := 0; i < size; i += 8 {
		binary.LittleEndian.PutUint64(out[i:], r.u64())
	}
	if ver > 0 {
		m := rng{s: 0xb10c}
		for k := 0; k < 200; k++ {
			at := m.n(size-4096) &^ 7
			for i := 0; i < 4096; i += 8 {
				binary.LittleEndian.PutUint64(out[at+i:], m.u64())
			}
		}
	}
	return out
}

func utf16File(s string, order binary.ByteOrder, bom bool) []byte {
	var b bytes.Buffer
	if bom {
		binary.Write(&b, order, uint16(0xfeff))
	}
	binary.Write(&b, order, utf16.Encode([]rune(s)))
	return b.Bytes()
}

// legacy wraps bytes in a legacy encoding with ASCII lines around them, so
// the file is long enough to look like a source file.
func legacy(sample []byte) []byte {
	var b bytes.Buffer
	for i := 0; i < 120; i++ {
		fmt.Fprintf(&b, "line %03d: ", i)
		b.Write(sample)
		b.WriteString(" = value\n")
	}
	return b.Bytes()
}

